const DICTS = { en, ku, ar };
const listeners = new Set();

function loadLang() {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved && DICTS[saved]) return saved;
  } catch { /* ignore */ }
  return 'en';
}

let lang = loadLang();

export function getLang() {
  return lang;
}

export function getLangMeta() {
  return LANGS.find((l) => l.id === lang) || LANGS[0];
}

export function t(key, vars = {}) {
  const table = DICTS[lang] || en;
  let s = table[key] ?? en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    s = s.replaceAll(`{${k}}`, String(v ?? ''));
  }
  return s;
}

/** Translate if key exists, otherwise keep the catalog / character fallback string. */
export function tOpt(key, fallback, vars = {}) {
  const table = DICTS[lang] || en;
  if (table[key] == null && en[key] == null) return String(fallback ?? '');
  return t(key, vars);
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

function applyDir() {
  const meta = getLangMeta();
  document.documentElement.lang = lang === 'ku' ? 'ckb' : lang;
  document.documentElement.dir = meta.dir;
  document.body.classList.toggle('rtl', meta.dir === 'rtl');
  document.body.classList.toggle('lang-ku', lang === 'ku');
  document.body.classList.toggle('lang-ar', lang === 'ar');
  document.body.classList.toggle('lang-en', lang === 'en');
}

/** Apply data-i18n / data-i18n-html / data-i18n-placeholder / data-i18n-title on a subtree. */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (!key) return;
    if (el.hasAttribute('data-i18n-html')) el.innerHTML = t(key);
    else el.textContent = t(key);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
  });
}

export function setLang(id) {
  if (!DICTS[id] || id === lang) {
    if (DICTS[id]) {
      applyDir();
      applyI18n();
    }
    return;
  }
  lang = id;
  try { localStorage.setItem(KEY, id); } catch { /* ignore */ }
  applyDir();
  applyI18n();
  for (const fn of listeners) {
    try { fn(lang); } catch { /* ignore */ }
  }
}

/** Build / refresh a <select> language control. */
export function bindLangSelect(select) {
  if (!select) return;
  select.innerHTML = LANGS.map((l) =>
    `<option value="${l.id}">${l.label}</option>`
  ).join('');
  select.value = lang;
  select.setAttribute('aria-label', t('nav.lang'));
  select.onchange = () => setLang(select.value);
}

export function initI18n() {
  applyDir();
  applyI18n();
}
